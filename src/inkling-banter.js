const storageKey = 'inkling-banter-history-v2';
const allLines = Object.values(banter).flat();
const catalog = new Set(allLines);
function browserStorage() {
  try { return globalThis.localStorage; } catch { return null; }
}

// A global history prevents context changes and reloads from recycling jokes.
// Prefer the current mood, then use another unseen line before repeating anything.
export function createBanter(random = Math.random, storage = browserStorage()) {
  let used = new Set(), last = null, lastRead;
  function read() {
    try {
      const raw = storage?.getItem(storageKey) || null;
      if (raw === lastRead) return;
      lastRead = raw;
      const saved = JSON.parse(raw || 'null');
      if (saved && Array.isArray(saved.used)) {
        used = new Set(saved.used.filter(text => catalog.has(text)));
        last = catalog.has(saved.last) ? saved.last : null;
      }
    } catch { /* Restricted storage still gets an in-memory non-repeating cycle. */ }
  }
  read();
  return context => {
    if (!banter[context]) throw new Error(`Unknown Inkling banter context: ${context}`);
    read(); // Also respect jokes already seen in another tab on this origin.
    if (used.size === catalog.size) used.clear();
    const preferred = context === 'poke'
      ? [...banter.poke, ...banter.corporate, ...banter.roam, ...banter.dodge]
      : banter[context];
    let pool = preferred.filter(text => !used.has(text) && text !== last);
    if (!pool.length) pool = allLines.filter(text => !used.has(text) && text !== last);
    const text = pool[Math.floor(random() * pool.length)];
    used.add(text); last = text;
    try {
      const serialized = JSON.stringify({used:[...used], last});
      storage?.setItem(storageKey, serialized);
      if (storage) lastRead = serialized;
    } catch {}
    return text;
  };
}
